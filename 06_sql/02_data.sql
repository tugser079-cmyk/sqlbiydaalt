INSERT INTO exhibit_location_history (exhibit_id, location_type, location_detail, start_date, end_date, handler_staff_id, notes)
SELECT 
    ((i % 15) + 1) AS exhibit_id,
    CASE (i % 4)
        WHEN 0 THEN 'STORAGE'
        WHEN 1 THEN 'EXHIBITION'
        WHEN 2 THEN 'LOAN'
        ELSE 'RESTORATION'
    END AS location_type,
    CONCAT('Эрдэнэт музейн архив байршил #', i, ' (Салбар-', (i % 5) + 1, ')') AS location_detail,
    (CURRENT_TIMESTAMP - ((250 - i) || ' days')::INTERVAL) AS start_date,
    (CURRENT_TIMESTAMP - ((250 - i - 1) || ' days')::INTERVAL) AS end_date,
    ((i % 15) + 1) AS handler_staff_id,
    CONCAT('Эрдэнэт үйлдвэрийн түүхийн сан хөмрөгийн автомат бүртгэл №', i) AS notes
FROM generate_series(1, 220) AS i;
